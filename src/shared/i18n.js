  const KEYS = [[/Strg/g, 'Ctrl'], [/Umschalt/g, 'Shift'], [/Entf\b/g, 'Del'], [/Pfeil/g, 'Arrow']]

  let lang = 'de'

  function fill (s, vars) {
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s
  }

  function t (s, vars) {
    if (s == null) return ''
    s = String(s)
    if (lang === 'en') {
      const hit = EN[s]
      if (hit !== undefined) return fill(hit, vars)
      for (const [re, rep] of KEYS) s = s.replace(re, rep)
    }
    return fill(s, vars)
  }

  // 'auto' folgt der Systemsprache: Deutsch bei de-*, sonst Englisch
  function resolve (setting, systemLocale) {
    if (setting === 'de' || setting === 'en') return setting
    return /^de\b/i.test(String(systemLocale || '')) ? 'de' : 'en'
  }

  function setLang (l) { lang = l === 'en' ? 'en' : 'de' }

  // Statische Texte einer Seite übersetzen: Textknoten sowie title/placeholder/aria-label,
  // deren (getrimmter) Inhalt genau einem Eintrag entspricht.
  function translateDom (rootEl) {
    if (lang === 'de' || !rootEl) return
    const doc = rootEl.ownerDocument || rootEl
    const walker = doc.createTreeWalker(rootEl, 4 /* NodeFilter.SHOW_TEXT */)
    for (let n = walker.nextNode(); n; n = walker.nextNode()) {
      const raw = n.nodeValue
      const key = raw.trim()
      const tr = key && t(key)
      if (tr && tr !== key) n.nodeValue = raw.replace(key, () => tr)
    }
    for (const el of rootEl.querySelectorAll ? rootEl.querySelectorAll('[title], [placeholder], [aria-label]') : []) {
      for (const a of ['title', 'placeholder', 'aria-label']) {
        const v = el.getAttribute(a)
        if (v) el.setAttribute(a, t(v))
      }
    }
    if (doc.title) doc.title = t(doc.title)
    if (doc.documentElement) doc.documentElement.lang = lang
  }

  const api = {
    EN,
    t,
    resolve,
    setLang,
    translateDom,
    get lang () { return lang },
    get locale () { return lang === 'en' ? 'en-US' : 'de-DE' }
  }
  if (typeof module === 'object' && module.exports) module.exports = api
  else root.CaravelI18n = api
